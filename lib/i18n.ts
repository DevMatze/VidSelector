export const dictionaries: Record<UiLanguage, Dictionary> = { de, en, es, fr };

export function translate(language: UiLanguage, key: string, values: Values = {}): string {
  const template = dictionaries[language][key] ?? dictionaries.en[key] ?? dictionaries.de[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
